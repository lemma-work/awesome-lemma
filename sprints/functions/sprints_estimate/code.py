"""Set a team task's estimate, in points (the plan screen's 1–5 keys, or chat:
"estimate #444 at 3"). `points` null clears it.

In a sprint being planned the new estimate is the plan's. In a running sprint
"in at start" stays what it was at the start; the change is written as an
`estimated` event (from, to), and the scope graph moves by the difference.
"""

from __future__ import annotations

from lemma_sdk import FunctionContext
from pydantic import BaseModel


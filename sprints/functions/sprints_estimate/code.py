class SprintsEstimateInput(BaseModel):
    task: str
    points: float | None = None


class SprintsEstimateResult(BaseModel):
    task_id: str | None
    points: float | None
    message: str


def sprints_estimate(ctx: FunctionContext, data: SprintsEstimateInput) -> SprintsEstimateResult:
    pod = ctx.pod
    ref = str(data.task).strip().lstrip("#")
    found = q(pod, f"SELECT id, number FROM task WHERE {'number = ' + ref if ref.isdigit() else 'id = ' + lit(ref)}")
    if not found:
        return SprintsEstimateResult(task_id=None, points=None, message="No team task found.")
    task = found[0]
    if data.points is not None and (data.points < 0 or data.points > 100):
        return SprintsEstimateResult(task_id=task["id"], points=None, message="An estimate is between 0 and 100 points.")
    old = q(pod, f"SELECT points FROM sprints_estimate WHERE id = {lit(task['id'])}")
    before = float(old[0]["points"]) if old else None
    if before == data.points:
        return SprintsEstimateResult(task_id=task["id"], points=data.points, message="No change.")
    now = now_iso()
    who = ctx.user_name or (ctx.user_email or "").split("@")[0] or None
    if data.points is None:
        if old:
            pod.records.bulk_delete("sprints_estimate", [task["id"]])
    else:
        pod.records.bulk_create("sprints_estimate", [{"id": task["id"], "points": data.points, "by": who,
                                                      "by_user_id": str(ctx.user_id) if ctx.user_id else None, "at": now}],
                                upsert=True)
    items = q(pod, "SELECT i.id, i.sprint_id, s.state FROM sprints_item i JOIN sprints_sprint s ON s.id = i.sprint_id "
                   f"WHERE i.task_id = {lit(task['id'])} AND i.removed_at IS NULL AND s.state <> 'closed'")
    events, plan = [], []
    for i in items:
        if i["state"] == "planned":
            plan.append({"id": i["id"], "points_at_add": data.points})
        else:
            events.append({"id": sid("event", i["id"], "estimated", now), "sprint_id": i["sprint_id"], "task_id": task["id"],
                           "kind": "estimated", "at": now, "via": "app", "actor_kind": "person" if ctx.user_id else "lemma",
                           "actor_name": who, "actor_user_id": str(ctx.user_id) if ctx.user_id else None,
                           "detail": {"from": before, "to": data.points}})
    if plan:
        pod.records.bulk_update("sprints_item", plan)
    if events:
        pod.records.bulk_create("sprints_event", events, upsert=True)
    said = "cleared" if data.points is None else f"{num(data.points)} pts"
    return SprintsEstimateResult(task_id=task["id"], points=data.points, message=f"#{task['number']}: {said}.")

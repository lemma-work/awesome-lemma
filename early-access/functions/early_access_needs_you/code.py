# contract:needs-you
# The one way to write `needs_you` (see _contract/README.md). Copied verbatim
# into every writer between these markers; _contract/lint.py fails on any
# difference. Needs a grant on needs_you (read and write).
import uuid as _ny_uuid
from datetime import datetime as _ny_datetime, timezone as _ny_timezone

NEEDS_YOU_NS = _ny_uuid.UUID("6b1d9a2e-4c37-4f0a-9e58-2d7c1b3f8a65")


def needs_you_id(plugin: str, table: str, source_id: str, verb: str, member: str) -> str:
    """The item's id: one per (plugin, source table, source row, verb, member)."""
    return str(_ny_uuid.uuid5(NEEDS_YOU_NS, f"{plugin}/{table}/{source_id}/{verb}/{member}"))


def needs_you_write(pod, plugin: str, member: str, items: list, scope_where: str | None = None) -> dict:
    """Write what needs the member now, from one plugin, and resolve the rest.

    `items` are the plugin's current items within the scope, each with verb,
    title, source_table, source_id and source_version, and any other column.
    `scope_where` is a SQL condition on needs_you naming what this pass looked
    at (e.g. "conversation_id IN (...)"); None means everything of this plugin.

    - new: created open.
    - open or snoozed: updated in place (a snooze holds until it ends).
    - dismissed, or done by the person: left alone, unless source_version
      changed, when it opens again.
    - done by the source (resolved before): opens again.
    - open or snoozed items in scope that are no longer current: done, closed
      by the source.
    """
    def rows(response):
        payload = response.to_dict() if hasattr(response, "to_dict") else response
        return [r for r in (payload or {}).get("items", []) if isinstance(r, dict)]

    def quoted(value):
        return "'" + str(value).replace("'", "''") + "'"

    now = _ny_datetime.now(_ny_timezone.utc).isoformat()
    current = {}
    for item in items:
        row = dict(item, source_plugin=plugin)
        row["id"] = needs_you_id(plugin, row["source_table"], str(row["source_id"]), row["verb"], member)
        current[row["id"]] = row
    where = f"source_plugin = {quoted(plugin)}" + (f" AND ({scope_where})" if scope_where else "")
    seen = {r["id"]: r for r in rows(pod.query(
        f"SELECT id, state, closed_by, source_version, snoozed_until FROM needs_you WHERE {where} LIMIT 5000"))}
    missing = [i for i in current if i not in seen]
    for start in range(0, len(missing), 200):
        ids = ", ".join(quoted(i) for i in missing[start : start + 200])
        seen.update({r["id"]: r for r in rows(pod.query(
            f"SELECT id, state, closed_by, source_version, snoozed_until FROM needs_you WHERE id IN ({ids})"))})
    creates, updates, counts = [], [], {"created": 0, "updated": 0, "kept_closed": 0, "resolved": 0}
    for item_id, row in current.items():
        old = seen.get(item_id)
        if old is None:
            creates.append(dict(row, state="open"))
            continue
        changed = (old.get("source_version") or "") != (row.get("source_version") or "")
        state = old.get("state")
        if state in ("dismissed", "done") and old.get("closed_by") != "source" and not changed:
            counts["kept_closed"] += 1
            continue
        if state == "snoozed" and not changed and (old.get("snoozed_until") or "") > now:
            updates.append(row)
            continue
        updates.append(dict(row, state="open", closed_by=None, snoozed_until=None))
    for item_id, old in seen.items():
        if item_id not in current and old.get("state") in ("open", "snoozed"):
            updates.append({"id": item_id, "state": "done", "closed_by": "source"})
            counts["resolved"] += 1
    for start in range(0, len(creates), 100):
        pod.records.bulk_create("needs_you", creates[start : start + 100], upsert=True)
    for start in range(0, len(updates), 100):
        pod.records.bulk_update("needs_you", updates[start : start + 100])
    counts["created"], counts["updated"] = len(creates), len(updates) - counts["resolved"]
    return counts
# end contract


class EarlyAccessNeedsYouInput(BaseModel):
    pass


class EarlyAccessNeedsYouResult(BaseModel):
    items: int = 0
    counts: dict = {}


def early_access_needs_you(ctx: FunctionContext, data: EarlyAccessNeedsYouInput) -> EarlyAccessNeedsYouResult:
    pod = ctx.pod
    me = str(ctx.user_id)
    items = []
    betas = [dict(b) for b in q(pod, f"SELECT * FROM early_access_beta WHERE owner_user_id = {lit(me)} AND state IN ('open', 'paused') LIMIT 20")]
    drafts = [dict(d) for d in q(pod, "SELECT id, state, built_from FROM draft WHERE state = 'proposed' LIMIT 1000")]
    by_kind: dict[tuple, int] = {}
    for d in drafts:
        b = jl(d.get("built_from"), {}) or {}
        if b.get("plugin") == PLUGIN:
            by_kind[(b.get("beta_id"), b.get("kind"))] = by_kind.get((b.get("beta_id"), b.get("kind")), 0) + 1
    since = (now() - _timedelta(days=7)).isoformat()
    for beta in betas:
        bid, name, path = beta["id"], beta["name"], f"/b/{beta['id']}"
        counts = {r["status"]: int(r["n"]) for r in q(pod, f"SELECT status, COUNT(*) AS n FROM early_access_tester WHERE beta_id = {lit(bid)} GROUP BY status")}
        fit_ready = q(pod, f"SELECT COUNT(*) AS n FROM early_access_tester WHERE beta_id = {lit(bid)} AND status = 'waiting' AND fit IN ('strong', 'maybe')")
        ready = int((fit_ready[0] if fit_ready else {}).get("n") or 0)
        size = int(beta.get("batch_size") or 10)
        last = q(pod, f"SELECT id FROM early_access_batch WHERE beta_id = {lit(bid)} ORDER BY picked_at DESC LIMIT 1")
        if ready and not counts.get("picked"):
            n = min(size, ready)
            items.append({"verb": "decide", "source_table": "early_access_beta", "source_id": f"{bid}#next",
                          "source_version": f"{(last[0]['id'] if last else 'none')}", "title": f"Next {n} for {name} {'is' if n == 1 else 'are'} ready",
                          "why": f"{counts.get('waiting', 0)} waiting, ranked by fit with a reason each. Nobody is let in until you press.",
                          "app": APP, "path": f"{path}/next", "weight": 3.0, "since_at": now_iso()})
        for kind, words, weight in (("invite", "{n} invites for {name} are ready to send", 4.0),
                                    ("checkin", "{n} check-ins for {name} are drafted", 2.0),
                                    ("chase", "{n} people went quiet in {name}: notes drafted", 2.5)):
            n = by_kind.get((bid, kind), 0)
            if n:
                items.append({"verb": "decide", "source_table": "early_access_beta", "source_id": f"{bid}#{kind}", "source_version": str(n),
                              "title": words.format(n=n, name=name), "why": "Drafted in your mailbox; nothing goes until you press Send.",
                              "prepared": "Drafted", "app": APP, "path": path, "weight": weight})
        if beta.get("feature_id"):
            blk = q(pod, f"SELECT id, quote FROM feedback WHERE plugin = {lit(PLUGIN)} AND feature_id = {lit(beta['feature_id'])} "
                         f"AND importance = 'blocker' AND said_at >= {lit(since)} ORDER BY said_at DESC LIMIT 50")
            if blk:
                items.append({"verb": "decide", "source_table": "early_access_beta", "source_id": f"{bid}#blockers",
                              "source_version": blk[0]["id"], "title": f"{len(blk)} new {'blocker' if len(blk) == 1 else 'blockers'} from {name} testers",
                              "why": "What stops them using it, in their words.", "quote": clip(blk[0].get("quote"), 600),
                              "app": APP, "path": path, "weight": 3.5})
    counts = needs_you_write(pod, PLUGIN, me, items)
    return EarlyAccessNeedsYouResult(items=len(items), counts=counts)

"""What in Early access needs this person, in the shared `needs_you` list
Today reads: one `decide` item per beta and kind, never one per tester, for
the betas they own (and the drafts in their own mailbox):

    next      "Next 10 for <beta> are ready" while people wait with a fit and
              nobody picked is still waiting for Send
    invites   "N invites for <beta> are ready to send"
    checkins  "N check-ins for <beta> are drafted"
    quiet     "N people went quiet in <beta>: notes drafted"
    blockers  "N new blockers from <beta> testers" (feedback in 7 days)

Runs as the person (the end of their sweep, a sign-up, the app on open);
resolves what no longer applies. Done or Not now in Today settles an item
until its source changes.
"""


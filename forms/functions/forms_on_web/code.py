class FormsOnWebInput(BaseModel):
    table: str
    record_id: str
    row_author: str | None = None
    payload: dict | None = None


class FormsOnWebResult(BaseModel):
    answer_id: str | None = None
    created: bool = False
    message: str


def fields_of(table: str, form: dict, row: dict) -> list:
    """The row as [{label, key, value, type}], in the form's order (a team's renamed labels first)."""
    order = [(f.get("key"), f.get("label")) for f in form.get("fields") or [] if f.get("key") and f.get("on", True) is not False] \
        or LABELS.get(table, [])
    seen, out = set(), []
    for key, label in order:
        if key in SKIP or key in seen:
            continue
        seen.add(key)
        value = row.get(key)
        if value in (None, ""):
            continue
        kind = "file" if key in FILE_KEYS else ("email" if "email" in key else "text")
        out.append({"label": label or key, "key": key, "value": str(value)[:5000] if not isinstance(value, (int, float, bool)) else value, "type": kind})
    for key, value in row.items():  # a column the team added that the form doesn't list yet
        if key in SKIP or key in seen or value in (None, "") or key.startswith("_"):
            continue
        out.append({"label": key.replace("_", " ").capitalize(), "key": key, "value": str(value)[:5000], "type": "text"})
    return out


def forms_on_web(ctx: FunctionContext, data: FormsOnWebInput) -> FormsOnWebResult:
    pod = ctx.pod
    if data.table not in STARTERS:
        return FormsOnWebResult(message=f"{data.table} isn't one of Forms' web forms.")
    row = dict(data.payload or {})
    if not row.get("email") and not row.get("name"):
        found = q(pod, f"SELECT * FROM {data.table} WHERE id = {lit(data.record_id)}")
        row = dict(found[0]) if found else row
    if not row:
        return FormsOnWebResult(message="No such answer.")
    if row.get("answer_id"):
        return FormsOnWebResult(answer_id=str(row["answer_id"]), message="Already filed.")
    form = get_form(pod, form_id("web", data.table)) or get_form(pod, data.table)
    if not form:
        name, purpose, _wf = STARTERS[data.table]
        s = settings_of(pod)
        form = {"id": form_id("web", data.table), "name": name, "source": "web", "source_id": data.table, "owner_plugin": APP,
                "purpose": purpose, "state": "on", "reply_mode": "draft", "default_owner_user_id": s.get("steward_user_id"),
                "held_by_user_id": s.get("steward_user_id"), "fields": [{"key": k, "label": l, "order": i} for i, (k, l) in enumerate(LABELS[data.table])]}
        pod.records.bulk_create("form", [{k: v for k, v in form.items() if v is not None}], upsert=True)
        form = form_of(form)
    author = str(data.row_author or row.get("_row_author") or "")
    contact_id = author.split(":", 1)[1] if author.startswith("contact:") else None
    fields = fields_of(data.table, form, row)
    files = [str(row[k]) for k in FILE_KEYS if row.get(k)]
    came_from = {k: row.get(k) for k in ("page", "campaign") if row.get(k)}
    out = file_answer(pod, form, str(data.record_id), fields, received_at=row.get("created_at") or now_iso(), name=row.get("name"),
                      handle=row.get("email"), company=row.get("company"), contact_id=contact_id,
                      row_author=author or "visitor", files=files, came_from=came_from)
    try:
        pod.table(data.table).update(data.record_id, {"answer_id": out["answer"]["id"]})
    except Exception:  # noqa: BLE001 - the answer is filed either way
        pass
    a = out["answer"]
    return FormsOnWebResult(answer_id=a["id"], created=out["created"],
                            message=(f"Filed {a.get('name') or 'an answer'}'s answer to {form.get('name')}." if out["created"] else "Already filed."))

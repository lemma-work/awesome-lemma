"""A visitor sent one of the starter web forms: its row in forms_contact,
forms_demo, forms_careers or forms_beta (the forms-web-<form> trigger, made
by the app with include_outside_rows by whoever turned the form on, so the
run is theirs). Writes one form_answer, state new; forms-read reads and
routes it.

Who it is from: the contact the platform names on the insert event
(`row_author` "contact:<id>": a confirmed email or a host token), else the
email typed. The row's words are someone else's: they are filed as data and
never followed. A file stays where the platform put it, in /forms/<table>,
linked and never read.
"""


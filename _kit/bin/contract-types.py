#!/usr/bin/env python3
"""Write src/contract.ts from ../_contract/tables, so the row types every app
uses for the shared tables are the contract itself and cannot drift from it.

Run by bin/pack.sh; by hand: uv run --no-project python bin/contract-types.py
"""
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(HERE.parent / "_contract"))
from lint import jsonc  # noqa: E402  (the one JSONC reader)

TYPES = {"TEXT": "string", "UUID": "string", "DATETIME": "string", "DATE": "string", "FILE_PATH": "string",
         "INTEGER": "number", "FLOAT": "number", "BOOLEAN": "boolean", "JSON": "unknown"}
JSON_OVERRIDES = {"to_handles": "string[]", "cc_handles": "string[]", "participants": "string[]", "built_from": "string[]", "labels": "string[]"}


def pascal(name: str) -> str:
    return "".join(part.capitalize() for part in name.split("_"))


def render() -> str:
    lines = [
        "// Generated by bin/contract-types.py from plugins/_contract/tables. Do not edit:",
        "// change the contract, then run bin/pack.sh.",
        "",
    ]
    for path in sorted((HERE.parent / "_contract" / "tables").glob("*.json")):
        spec = jsonc(path.read_text())
        lines.append(f"/** A row of the shared `{spec['name']}` table. */")
        lines.append(f"export interface {pascal(spec['name'])}Row {{")
        lines.append("  id: string;")
        for column in spec["columns"]:
            if column["type"] == "ENUM":
                kind = " | ".join(json.dumps(o) for o in column["options"])
            elif column["type"] == "JSON":
                kind = JSON_OVERRIDES.get(column["name"], "unknown")
            else:
                kind = TYPES.get(column["type"], "unknown")
            optional = "" if column.get("required") else "?"
            nullable = "" if column.get("required") else " | null"
            lines.append(f"  {column['name']}{optional}: {kind}{nullable};")
        # The platform's own timestamps, unless the table declares one itself.
        declared = {column["name"] for column in spec["columns"]}
        lines += [f"  {name}?: string;" for name in ("created_at", "updated_at") if name not in declared]
        lines += ["}", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    (HERE / "src" / "contract.ts").write_text(render())
    print("wrote src/contract.ts")

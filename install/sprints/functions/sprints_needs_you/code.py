"""What in Sprints needs the sprint lead, written to the shared `needs_you`
list Today reads (see _contract/README.md, "Needs you"). Every item is a
`decide`:

  Plan Sprint N     two days before a planned sprint starts, until it starts
  Close Sprint N    from the running sprint's last day until it is closed
  #444 came in: pull it into Sprint N?
                    urgent or high work from a watched source (Incidents,
                    Triage, PR review) that landed mid-sprint, until the lead
                    pulls it in or says not now

Runs as the person (their app, their daily run, the trigger on a new
suggestion that the app made as the lead). `needs_you` is row-level: a run
writes only its own person's items, so only the lead's own runs write these;
anyone else's run resolves whatever Sprints had left them (a lead who handed
the role on).
"""


class FormsUnsureSweepInput(BaseModel):
    pass


class FormsUnsureSweepResult(BaseModel):
    moved: int = 0
    broken: int = 0
    message: str


def forms_unsure_sweep(ctx: FunctionContext, data: FormsUnsureSweepInput) -> FormsUnsureSweepResult:
    pod = ctx.pod
    s = settings_of(pod)
    if not s.get("setup_done_at"):
        return FormsUnsureSweepResult(message="Forms isn't set up yet.")
    cutoff = (now() - timedelta(minutes=s["unsure_after_minutes"])).isoformat()
    moved = 0
    for r in q(pod, f"SELECT * FROM form_answer WHERE state = 'unsure' AND COALESCE(sample, FALSE) = FALSE "
                    f"AND COALESCE(received_at, created_at) < {lit(cutoff)} LIMIT 200"):
        a = answer_of(r)
        form = get_form(pod, a["form_id"]) or {}
        owner = a.get("owner_user_id") or form.get("default_owner_user_id") or s.get("steward_user_id")
        name = member_name(s, owner, a.get("owner_name") or "the default owner")
        said = f"Nobody picked where it goes within {minutes_words(s['unsure_after_minutes'])}, so it's with {first_name(name)}, still marked not sure"
        pod.table("form_answer").update(a["id"], {
            "state": "routed", "routed_to": "forms", "owner_user_id": owner, "owner_name": name, "owner_why": clip(said, 300),
            "owner_rule": "default", "hand_version": a["hand_version"] + 1, "draft_state": "none",
            "rules_checked": [{"rule": "Not sure for an hour", "result": "used", "said": said}]})
        add_events(pod, a["id"], [{"kind": "routed", "key": f"unsure:{a['hand_version']}", "text": said + "."}])
        moved += 1
    broken = 0
    stale = (now() - timedelta(hours=1)).isoformat()
    for f in q(pod, "SELECT id, name, source, last_read_at FROM form WHERE state = 'on' AND source IN ('google_forms', 'meta_ads') "
                    f"AND last_read_at IS NOT NULL AND last_read_at < {lit(stale)} LIMIT 100"):
        pod.table("form").update(f["id"], {"state": "broken", "state_why": clip(f"Not read since {str(f['last_read_at'])[:16].replace('T', ' ')}: the reading stopped", 300)})
        broken += 1
    return FormsUnsureSweepResult(moved=moved, broken=broken, message=f"Moved {moved} not-sure answer(s); {broken} door(s) marked broken.")

# contract:needs-you
# The one way to write `needs_you` (see _contract/README.md). Copied verbatim
# into every writer between these markers; _contract/lint.py fails on any
# difference. Needs a grant on needs_you (read and write).
import uuid as _ny_uuid
from datetime import datetime as _ny_datetime, timezone as _ny_timezone

NEEDS_YOU_NS = _ny_uuid.UUID("6b1d9a2e-4c37-4f0a-9e58-2d7c1b3f8a65")


def needs_you_id(plugin: str, table: str, source_id: str, verb: str, member: str) -> str:
    """The item's id: one per (plugin, source table, source row, verb, member)."""
    return str(_ny_uuid.uuid5(NEEDS_YOU_NS, f"{plugin}/{table}/{source_id}/{verb}/{member}"))


def needs_you_write(pod, plugin: str, member: str, items: list, scope_where: str | None = None) -> dict:
    """Write what needs the member now, from one plugin, and resolve the rest.

    `items` are the plugin's current items within the scope, each with verb,
    title, source_table, source_id and source_version, and any other column.
    `scope_where` is a SQL condition on needs_you naming what this pass looked
    at (e.g. "conversation_id IN (...)"); None means everything of this plugin.

    - new: created open.
    - open or snoozed: updated in place (a snooze holds until it ends).
    - dismissed, or done by the person: left alone, unless source_version
      changed, when it opens again.
    - done by the source (resolved before): opens again.
    - open or snoozed items in scope that are no longer current: done, closed
      by the source.
    """
    def rows(response):
        payload = response.to_dict() if hasattr(response, "to_dict") else response
        return [r for r in (payload or {}).get("items", []) if isinstance(r, dict)]

    def quoted(value):
        return "'" + str(value).replace("'", "''") + "'"

    now = _ny_datetime.now(_ny_timezone.utc).isoformat()
    current = {}
    for item in items:
        row = dict(item, source_plugin=plugin)
        row["id"] = needs_you_id(plugin, row["source_table"], str(row["source_id"]), row["verb"], member)
        current[row["id"]] = row
    where = f"source_plugin = {quoted(plugin)}" + (f" AND ({scope_where})" if scope_where else "")
    seen = {r["id"]: r for r in rows(pod.query(
        f"SELECT id, state, closed_by, source_version, snoozed_until FROM needs_you WHERE {where} LIMIT 5000"))}
    missing = [i for i in current if i not in seen]
    for start in range(0, len(missing), 200):
        ids = ", ".join(quoted(i) for i in missing[start : start + 200])
        seen.update({r["id"]: r for r in rows(pod.query(
            f"SELECT id, state, closed_by, source_version, snoozed_until FROM needs_you WHERE id IN ({ids})"))})
    creates, updates, counts = [], [], {"created": 0, "updated": 0, "kept_closed": 0, "resolved": 0}
    for item_id, row in current.items():
        old = seen.get(item_id)
        if old is None:
            creates.append(dict(row, state="open"))
            continue
        changed = (old.get("source_version") or "") != (row.get("source_version") or "")
        state = old.get("state")
        if state in ("dismissed", "done") and old.get("closed_by") != "source" and not changed:
            counts["kept_closed"] += 1
            continue
        if state == "snoozed" and not changed and (old.get("snoozed_until") or "") > now:
            updates.append(row)
            continue
        updates.append(dict(row, state="open", closed_by=None, snoozed_until=None))
    for item_id, old in seen.items():
        if item_id not in current and old.get("state") in ("open", "snoozed"):
            updates.append({"id": item_id, "state": "done", "closed_by": "source"})
            counts["resolved"] += 1
    for start in range(0, len(creates), 100):
        pod.records.bulk_create("needs_you", creates[start : start + 100], upsert=True)
    for start in range(0, len(updates), 100):
        pod.records.bulk_update("needs_you", updates[start : start + 100])
    counts["created"], counts["updated"] = len(creates), len(updates) - counts["resolved"]
    return counts
# end contract


class KnowhowMineInput(BaseModel):
    detail: bool = False
    tell: bool = True


class KnowhowMineResult(BaseModel):
    count: int = 0
    counts: dict = {}
    told: int = 0
    items: list[dict] = []
    message: str


def items_for(me: str, s: dict, today, person: dict, mine_topics: list, misses: list, drafts: list, changes: list,
              arts: list, assigns: list, by_id: dict) -> list:
    out = []
    topic_ids = {str(t["id"]) for t in mine_topics}
    for qn in misses:
        if str(qn.get("owner_member_id") or "") != me and str(qn.get("topic_id") or "") not in topic_ids:
            continue
        n = int(qn.get("times") or 1)
        what = clip(qn.get("text"), 120)
        title = f"{n} people asked: “{what}”" if n > 1 else f"Someone asked: “{what}”"
        out.append({"verb": "answer", "title": clip(title, 300),
                    "why": clip(("Partly in a file. " if qn.get("outcome") == "partly" else "") + "No page answers it yet; your reply becomes the answer.", 300),
                    "quote": None if qn.get("sensitive") else clip(qn.get("text"), 600),
                    "source_table": "knowhow_question", "source_id": str(qn["id"]), "source_version": f"{qn.get('state')}:{n}",
                    "app": APP, "path": f"/q/{qn['id']}", "since_at": iso(qn.get("asked_at")), "weight": 4 + min(n, 5) / 10})
    for d in drafts:
        if str(d.get("owner_member_id") or "") != me:
            continue
        reply = d.get("source") == "reply"
        first = d.get("_question")
        out.append({"verb": "decide", "title": clip("Save the answer from your reply" if reply else f"Save the draft “{d.get('title')}”", 300),
                    "why": clip(f"{d.get('title')}" + (f" · asked {first.get('times')} times" if first and int(first.get('times') or 1) > 1 else ""), 300),
                    "source_table": "knowhow_article", "source_id": str(d["id"]), "source_version": f"draft:{d.get('checked_hash') or d.get('updated_at') or ''}"[:200],
                    "app": APP, "path": f"/q/{first['id']}" if first else f"/p/{d['id']}", "weight": 5,
                    "prepared": "Drafted by the Lemma", "prepared_text": clip(d.get("quote") or d.get("title"), 2000)})
    for ch in changes:
        a = by_id.get(str(ch.get("article_id")))
        if not a or str(a.get("owner_member_id") or "") != me:
            continue
        if ch.get("kind") == "may_disagree":
            why = json_obj(ch.get("evidence")).get("why") or "Its file changed since it was checked."
            title = f"“{a.get('title')}” may disagree with the new text"
        else:
            why = clip(json_obj(ch.get("evidence")).get("quote") or ch.get("text"), 300)
            title = f"A proposed change to “{a.get('title')}”" + (f", step {ch['step']}" if ch.get("step") else "")
        out.append({"verb": "decide", "title": clip(title, 300), "why": clip(why, 300), "source_table": "knowhow_change",
                    "source_id": str(ch["id"]), "source_version": f"{ch.get('state')}", "app": APP, "path": f"/p/{a['id']}", "weight": 4})
    customers_on = bool(s["audiences"].get("customers") or s["audiences"].get("public"))
    weekly_ok = person.get("check_rhythm") != "weekly" or today.weekday() == int(person.get("check_day") or 0)
    late = [a for a in arts if str(a.get("owner_member_id") or "") == me and a.get("kind") != "sheet" and a.get("state") in LIVE_STATES and is_late(a, today)]
    if late and weekly_ok:
        ids = sorted(str(a["id"]) for a in late)
        out.append({"verb": "do", "title": clip(f"{plural(len(late), 'answer')} of yours {'is' if len(late) == 1 else 'are'} past {'its' if len(late) == 1 else 'their'} check date", 300),
                    "why": clip(", ".join(a.get("title") or "" for a in late[:4]) + ("…" if len(late) > 4 else ""), 300),
                    "source_table": "knowhow_article", "source_id": f"due:{me}", "source_version": sha(",".join(ids))[:32],
                    "app": APP, "path": "/library/mine", "weight": 3})
    lead = int(s.get("customer_lead_days") or 14)
    for a in arts:
        if str(a.get("owner_member_id") or "") != me or a.get("audience") not in ("customers", "public") or a.get("state") != "live":
            continue
        due = day_of(a.get("due_on"))
        if due and today < due <= today + _timedelta(days=lead) and customers_on:
            out.append({"verb": "do", "title": clip(f"“{a.get('title')}” leaves the customer answers on {fmt_day(due)} unless checked", 300),
                        "why": "Customers only get answers in date. Keep it to check it.", "source_table": "knowhow_article",
                        "source_id": str(a["id"]), "source_version": f"leaving:{due}", "app": APP, "path": f"/p/{a['id']}",
                        "due_at": iso(due), "weight": 3.5})
        topic = a.get("_topic") or {}
    for a in arts:
        topic = a.get("_topic") or {}
        if (customers_on and str(a.get("owner_member_id") or "") == me and a.get("state") == "live" and a.get("audience") == "team"
                and topic.get("audience_default") in ("customers", "public") and not a.get("approved_at")):
            out.append({"verb": "decide", "title": clip(f"Approve “{a.get('title')}” for customers", 300),
                        "why": f"{topic.get('name')} is a topic customers may read.", "source_table": "knowhow_article",
                        "source_id": f"approve:{a['id']}", "source_version": f"approve:{a.get('checked_hash') or ''}"[:200],
                        "app": APP, "path": f"/p/{a['id']}", "weight": 2})
    for g in assigns:
        a = by_id.get(str(g.get("article_id")))
        if not a:
            continue
        out.append({"verb": "do", "title": clip(f"Walk “{a.get('title')}”" + (f" (assigned by {first_name(g.get('assigned_by_name'))})" if g.get("assigned_by_name") else ""), 300),
                    "why": f"{len(a.get('steps') or [])} steps · in Teams or here", "source_table": "knowhow_assignment", "source_id": str(g["id"]),
                    "source_version": str(g.get("state")), "app": APP, "path": f"/p/{a['id']}/walk", "due_at": iso(g.get("due_on")), "weight": 2.5})
    return out


def knowhow_mine(ctx: FunctionContext, data: KnowhowMineInput) -> KnowhowMineResult:
    pod = ctx.pod
    me = str(ctx.user_id) if getattr(ctx, "user_id", None) else ""
    if not me:
        return KnowhowMineResult(message="No member to write for.")
    s = settings_of(pod)
    today = today_of(s)
    person = (q(pod, f"SELECT * FROM knowhow_person WHERE member_id = {lit(me)} LIMIT 1") or [{}])[0]
    topics = topics_of(pod)
    tby = {str(t["id"]): t for t in topics}
    mine_topics = [t for t in topics if str(t.get("owner_member_id") or "") == me]
    misses = q(pod, "SELECT * FROM knowhow_question WHERE same_as IS NULL AND state IN ('new', 'asked') "
                    "AND outcome IN ('missed', 'partly', 'wrong', 'passed_on') AND draft_article_id IS NULL ORDER BY asked_at DESC LIMIT 300")
    arts = [article_of(r) for r in q(pod, f"SELECT * FROM knowhow_article WHERE owner_member_id = {lit(me)} AND state <> 'retired' LIMIT 2000")]
    for a in arts:
        a["_topic"] = tby.get(str(a.get("topic_id")), {})
    by_id = {str(a["id"]): a for a in arts}
    drafts = [a for a in arts if a.get("state") == "draft"]
    if drafts:
        for r in q(pod, f"SELECT id, times, draft_article_id FROM knowhow_question WHERE draft_article_id IN ({lits([d['id'] for d in drafts])}) "
                        "AND same_as IS NULL LIMIT 500"):
            d = by_id.get(str(r["draft_article_id"]))
            if d is not None and "_question" not in d:
                d["_question"] = r
    changes = q(pod, f"SELECT * FROM knowhow_change WHERE state = 'proposed' AND article_id IN ({lits(list(by_id))}) LIMIT 300") if by_id else []
    assigns = q(pod, f"SELECT * FROM knowhow_assignment WHERE member_id = {lit(me)} AND state <> 'done' LIMIT 100")
    if assigns:
        more = [article_of(r) for r in q(pod, f"SELECT * FROM knowhow_article WHERE id IN ({lits([g['article_id'] for g in assigns])}) LIMIT 100")]
        for a in more:
            by_id.setdefault(str(a["id"]), a)
    items = items_for(me, s, today, person, mine_topics, misses, drafts, changes, arts, assigns, by_id)
    counts = needs_you_write(pod, "know-how", me, [{k: v for k, v in i.items() if v is not None} for i in items], None)
    told = 0
    if data.tell:
        told = tell_me(pod, me, s)
    return KnowhowMineResult(count=len(items), counts=counts, told=told, items=items if data.detail else [],
                             message=(f"{len(items)} for you in Know-how." if items else "Nothing in Know-how needs you.")
                                     + (f" Told you about {plural(told, 'answer')}." if told else ""))


def tell_me(pod, me: str, s: dict) -> int:
    """A line in the person's own channel for each of their questions that now has an answer."""
    told = 0
    lines = []
    for r in q(pod, f"SELECT * FROM knowhow_question WHERE asked_by_member = {lit(me)} AND state IN ('saved', 'covered') AND told_at IS NULL LIMIT 20"):
        lines.append((r, None))
    try:
        mine = q(pod, "SELECT * FROM knowhow_my_question WHERE told_at IS NULL LIMIT 20")
    except Exception:  # noqa: BLE001
        mine = []
    if mine:
        by_q = {str(r["id"]): r for r in q(pod, f"SELECT * FROM knowhow_question WHERE id IN ({lits([m['question_id'] for m in mine])}) "
                                                 "AND state IN ('saved', 'covered') LIMIT 50")}
        lines += [(by_q[str(m["question_id"])], m) for m in mine if str(m["question_id"]) in by_q]
    for r, link in lines:
        a = find_article(pod, r.get("article_id")) if r.get("article_id") else None
        if not a or a.get("state") not in LIVE_STATES:
            continue
        text = f"Your question “{clip(r.get('text'), 140)}” has an answer now: “{a.get('title')}” in Know-how. {source_line(a)}"
        try:
            pod.channels.notify_me(text, idempotency_key=f"knowhow-told-{r['id']}")
        except Exception:  # noqa: BLE001
            continue
        if link:
            pod.table("knowhow_my_question").update(link["id"], {"told_at": now_iso()})
        else:
            pod.table("knowhow_question").update(r["id"], {"told_at": now_iso()})
            add_events(pod, "question", r["id"], [{"kind": "told", "key": "told", "text": "Told in their own Lemma channel."}])
        told += 1
    return told
